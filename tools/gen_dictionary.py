# Writes lean/MarkerDetect/MarkerDetect/Dictionary.lean from OpenCV's DICT_4X4_1000: all 1000 codes in all 4 rotations as 16-bit values
# (row-major, most significant bit first, 1 = white), exactly as OpenCV stores them, so the Lean decoder can be checked against it.
# python gen_dictionary.py <out.lean>
import sys, cv2, numpy as np, cv2.aruco as aruco
d = aruco.getPredefinedDictionary(aruco.DICT_4X4_1000); bl = d.bytesList            # (1000, 2, 4) uint8: 2 bytes per rotation
assert bl.shape == (1000, 2, 4), bl.shape
vals = []
for i in range(1000):
    for r in range(4): vals.append(int(bl[i, 0, r]) * 256 + int(bl[i, 1, r]))
with open(sys.argv[1], "w") as f:
    f.write("-- Generated by tools/gen_dictionary.py from OpenCV DICT_4X4_1000. Do not edit.\nnamespace MarkerDetect\n\nset_option maxRecDepth 100000\n\n")
    f.write("/-- Marker `i` in rotation `r` is `codes[4 * i + r]`: 16 bits, row-major, most significant bit first, 1 = white. -/\n")
    f.write("def codes : Array UInt16 := #[\n" + ",\n".join("  " + ", ".join(str(v) for v in vals[k:k + 16]) for k in range(0, len(vals), 16)) + "\n]\n\n")
    f.write("def markerCount : Nat := 1000\n\nend MarkerDetect\n")
print("wrote", sys.argv[1], len(vals), "codes; max correction bits OpenCV reports:", d.maxCorrectionBits)
